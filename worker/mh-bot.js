// ── Парсинг вебхука message.help ────────────────────────────────────────────
// Тело вебхука: { action: "channel.message.created", payload: ChannelMessage }.
function parseWebhook(body) {
  if (!body || body.action !== 'channel.message.created' || !body.payload) return null;
  const p = body.payload;
  return {
    messageId: p.id,
    userId: p.user_id,
    channelId: p.channel_id,
    text: (p.message || '').trim(),
    messageType: p.message_type || 'text',
    destination: p.destination || '',
    createdAt: p.created_at || '',
    fileUrl: p.file_url || '',   // голосовые/вложения: ссылка на файл (.oga для voice-note)
  };
}

// ── Обработка одного входящего сообщения ───────────────────────────────────
async function processMessage(msg, env) {
  const tag = `u${msg.userId}`;

  // Резолвим канал из входящего: проектный вебхук message.help ловит сообщения
  // со ВСЕХ каналов проекта, но мы обслуживаем только те, что в MH_CHANNELS.
  // Незнакомый канал (Instagram и т.п.) — молча скипаем.
  const channelUuid = resolveChannelUuid(env, msg.channelId);
  if (!channelUuid) {
    console.log(`unknown channel ${msg.channelId}, skip ${tag}`);
    return;
  }
  msg.channelUuid = channelUuid;

  // Эхо-защита: сообщение, отправленное самим ботом, message.help может вернуть
  // обратно вебхуком. Свои id мы помечаем при отправке — такие пропускаем.
  if (msg.messageId && await env.BOT_KV.get(`sent:${msg.messageId}`)) return;

  // Сотрудник подключился к чату — бот немедленно умолкает и больше не
  // перебивает. Сигналы message.help (подтверждено на проде в pulse-боте):
  //   from_whatsapp / from_instagram / from_operator / from_* — ИСХОДЯЩИЙ
  //     ответ человека через канал (раньше ловили только from_operator —
  //     реальные ответы менеджеров приходят как from_<канал>, и днём бот
  //     перебивал бы живой диалог);
  //   contact_in_work — сотрудник взял контакт в работу (ловим подключение
  //     ещё до того, как он что-то напишет).
  // Свои сообщения отсеяны эхо-защитой выше; на случай гонки «вебхук обогнал
  // запись sent:» — перепроверяем пометку после паузы, чтобы бот не заглушил
  // сам себя собственным эхом.
  const isOutboundEcho = typeof msg.destination === 'string'
    && msg.destination !== 'from' && msg.destination.startsWith('from_');
  if (isOutboundEcho || msg.destination === 'contact_in_work') {
    if (isOutboundEcho && msg.messageId) {
      await sleep(1500);
      if (await env.BOT_KV.get(`sent:${msg.messageId}`)) return; // своё эхо
    }
    if (msg.userId) {
      await env.BOT_KV.put(`op:${msg.userId}`, '1', { expirationTtl: OPERATOR_PAUSE_TTL });
      console.log(`operator joined -> bot paused ${tag} (${msg.destination})`);
    }
    return;
  }

  // Обрабатываем входящие сообщения клиента: ТЕКСТ и ГОЛОСОВЫЕ.
  // destination=from — «От пользователя». Всё прочее (to, notice_*, ai,
  // comment, altegio_*, ...) — исходящее/служебное/автоматическое, не наше.
  // Фото/видео/стикеры/документы — по-прежнему менеджерам (бот их не видит).
  if (msg.destination !== 'from') return;
  if (!msg.userId) return;
  const isVoice = isVoiceMessage(msg);
  if (!isVoice && msg.messageType !== 'text') return;
  if (!isVoice && !msg.text) return;

  // Дедуп — message.help может повторить доставку вебхука. ДО транскрипции
  // (не распознавать дважды) и ДО confirm_pending (не среагировать дважды
  // на ответ «Да/Нет»).
  const seenKey = `seen:${msg.messageId}`;
  if (await env.BOT_KV.get(seenKey)) return;
  await bumpStat(env, 'in');                            // воронка: входящее обработано

  // Голосовое → текст (Whisper, Workers AI). Удалось — сообщение дальше
  // живёт как обычный текст (включая «Да/Нет» на подтверждение записи).
  // Не удалось — placeholder: в confirm/engage-цепочках уйдёт менеджеру
  // стандартным follow-up'ом, в чате бота клиента вежливо попросим написать
  // текстом (фолбэк ниже, после проверок принадлежности чата).
  let voiceFailed = false;
  if (isVoice) {
    const transcript = await transcribeVoice(env, msg);
    if (transcript) {
      msg.text = transcript;
      console.log(`voice ok ${tag}: ${transcript.length} симв.`);
    } else {
      voiceFailed = true;
      msg.text = '[голосовое сообщение — распознать не удалось]';
      console.log(`voice FAIL ${tag}`);
    }
  }

  // Ответ клиента на подтверждение записи — НЕЗАВИСИМО от часа суток.
  // Цепочка должна быть доведена в любом случае: «Да» → attendance=2,
  // «Нет» → передача менеджеру, любой другой ответ («можно перенести?»,
  // «во сколько было?», «не уверена пока») → ТАКЖЕ передача менеджеру.
  // Раньше «другой» ответ проваливался в Claude-flow, а днём бот его
  // скипал по night-window → клиент оставался без ответа.
  const pendingRaw = await env.BOT_KV.get(`confirm_pending:user:${msg.userId}`);
  if (pendingRaw) {
    // В чат уже вступил человек-менеджер (op:-пауза выставляется, когда менеджер
    // пишет клиенту) — НЕ перебиваем его своей цепочкой подтверждения. Менеджер
    // доведёт сам; иначе бот и человек дублируют «подтвердите запись». Гасим
    // pending, отмечаем seen, молчим.
    if (await env.BOT_KV.get(`op:${msg.userId}`)) {
      await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });
      await env.BOT_KV.delete(`confirm_pending:user:${msg.userId}`);
      console.log(`confirm_pending: operator active -> bot silent ${tag}`);
      return;
    }
    let pending = null;
    try { pending = JSON.parse(pendingRaw); } catch (_) { pending = null; }
    const kind = classifyConfirmationResponse(msg.text);
    await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });
    if (kind === 'yes' || kind === 'no') {
      await handleConfirmationResponse(env, msg, kind, pending);
    } else if (arrivalWithinTolerance(msg.text, pending && pending.apptMin,
      Number(env.CONFIRM_LATE_TOLERANCE_MIN) || 10)) {
      // Не явное «да/нет», но клиент назвал время прихода в пределах допуска
      // опоздания (≤ N мин от брони) — считаем запись подтверждённой, менеджера
      // не дёргаем. Большее опоздание → handleConfirmationFollowUp (администратор).
      await handleConfirmationResponse(env, msg, 'yes', pending);
    } else if (isPoliteClosing(msg.text)) {
      // «Спасибо» / 🙏 — вежливое закрытие, менеджера не дёргаем.
      await env.BOT_KV.delete(`confirm_pending:user:${msg.userId}`);
      await sendMessage(env, msg, 'Будем рады видеть вас! 🌷');
    } else if (isQuestionOrRequest(msg.text)) {
      await handleConfirmationFollowUp(env, msg, pending);   // реальный вопрос/просьба → менеджер
    } else {
      // Приветствие / неясное, но НЕ вопрос — мягко переспрашиваем; pending
      // активен (следующее «Да/приеду» поймается). Один re-prompt, дальше → менеджер.
      const rk = `confirm_reprompt:${msg.userId}`;
      if (await env.BOT_KV.get(rk)) {
        await handleConfirmationFollowUp(env, msg, pending);
      } else {
        await env.BOT_KV.put(rk, '1', { expirationTtl: 7200 });
        await sendMessage(env, msg, 'Здравствуйте! 🌷 Подскажите, подтверждаете запись — придёте?');
      }
    }
    return;
  }

  // Ответ клиента на engage-сообщение рассылки акций. Так же круглосуточно.
  // «Да/+/интересно/расскажите» → отправляем полный шаблон акций (шаг 2).
  // «Нет/не нужно/отпишите» → opt-out на 365 дней + вежливый ответ.
  // Длинный/непонятный ответ → передаём менеджеру (он лучше отработает
  // вопросы про цену конкретной программы и т.п.).
  const engageRaw = await env.BOT_KV.get(`broadcast_engage_pending:user:${msg.userId}`);
  if (engageRaw) {
    // Менеджер уже в чате (op:-пауза) — не перебиваем ответом на акцию.
    if (await env.BOT_KV.get(`op:${msg.userId}`)) {
      await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });
      await env.BOT_KV.delete(`broadcast_engage_pending:user:${msg.userId}`);
      console.log(`engage_pending: operator active -> bot silent ${tag}`);
      return;
    }
    let engage = null;
    try { engage = JSON.parse(engageRaw); } catch (_) { engage = null; }
    const kind = classifyConfirmationResponse(msg.text);
    await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });
    if (kind === 'yes') {
      await handleBroadcastEngageYes(env, msg, engage);
    } else if (kind === 'no') {
      await handleBroadcastEngageNo(env, msg, engage);
    } else {
      await handleBroadcastEngageOther(env, msg, engage);
    }
    return;
  }

  // Окно лид-диалога: с 12.06.2026 BOT_HOUR_* = 0..24 (круглосуточно), бот
  // отвечает и днём — менеджер «выигрывает» чат первым же своим сообщением
  // (op:-пауза выше). Эхо-защита, операторская пауза и обработка ответа на
  // confirmation работают всегда, независимо от окна.
  const hour = almatyNow().hour;
  const inWindow = BOT_HOUR_START < BOT_HOUR_END
    ? (hour >= BOT_HOUR_START && hour < BOT_HOUR_END)
    : (hour >= BOT_HOUR_START || hour < BOT_HOUR_END);
  if (!inWindow) {
    console.log(`outside bot hours (h=${hour}, window=${BOT_HOUR_START}-${BOT_HOUR_END}), skip ${tag}`);
    return;
  }

  // Чат уже ведёт человек (сотрудник подключился, или бот ранее сделал
  // handoff) — бот не вмешивается.
  if (await env.BOT_KV.get(`op:${msg.userId}`)) {
    console.log(`paused, human owns ${tag}`);
    return;
  }

  // КЭВ уже состоялся (заявка передана менеджеру, kev_pending активен 48ч):
  // бот продолжает отвечать на уточнения («а парковка есть?»), но заявку
  // заново не собирает и ПОВТОРНЫХ карточек не создаёт.
  let kevPending = null;
  const kevPendingRaw = await env.BOT_KV.get(`kev_pending:${msg.userId}`);
  if (kevPendingRaw) {
    try { kevPending = JSON.parse(kevPendingRaw); } catch (_) { kevPending = {}; }
  }

  // Прерванный добор полей КЭВ с прошлого хода — напомним Claude, чего не хватает.
  let kevMissing = null;
  if (!kevPending) {
    const kevMissingRaw = await env.BOT_KV.get(`kev_missing:${msg.userId}`);
    if (kevMissingRaw) {
      try { kevMissing = JSON.parse(kevMissingRaw); } catch (_) { kevMissing = null; }
    }
  }

  // История диалога (baseLen — для защиты от гонки при записи).
  const histKey = `hist:${msg.userId}`;
  const histBefore = (await env.BOT_KV.get(histKey, { type: 'json' })) || [];
  const baseLen = histBefore.length;

  // Первый контакт бота с этим клиентом (истории ещё нет) — два гейта:
  if (baseLen === 0) {
    // 1) В этом чате сегодня-вчера уже отвечал ЧЕЛОВЕК (по журналу событий
    //    pulse-бота) — чат менеджера, бот не влезает. Без этого при дневном
    //    режиме бот перебивал бы живые диалоги, начатые до его включения.
    if (await humanOwnsDialog(env, msg.userId)) {
      await env.BOT_KV.put(`op:${msg.userId}`, '1', { expirationTtl: OPERATOR_PAUSE_TTL });
      console.log(`skip: human already in dialog ${tag} -> paused`);
      return;
    }
    // 2) Гейт «новый лид / действующий клиент» по РЕАЛЬНОЙ записи Altegio.
    //    Если у телефона есть запись на сегодня..+2 дня — это НЕ новый лид:
    //      • короткое «Приду/Да/Нет» → ответ на напоминание (внешнее — иначе
    //        сработал бы confirm_pending выше) → подтверждение/передача менеджеру;
    //      • иное (вопрос/просьба по своей записи) → вежливая передача администратору.
    //    Имя/противопоказания НЕ спрашиваем (собраны при записи). Гейт по РЕАЛЬНОЙ
    //    записи убирает регрессию: новый лид без записи сюда не попадает → лид-флоу.
    //    NB: это рабочая ЗАМЕНА прежнего classifyContact — clients/search в этом
    //    кабинете Altegio отдаёт 400 на quick_search и не возвращает visit_count,
    //    т.е. altegioHasVisitHistory молча возвращал 'new' (гейт не работал).
    const firstPhone = await getContactPhone(env, msg);
    const booking = firstPhone ? await altegioUpcomingBooking(env, firstPhone) : null;
    if (booking) {
      await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });
      const confirmKind = classifyConfirmationResponse(msg.text);
      const ap = parseAltegioParts(booking.date);
      const apptMin = ap ? ap.hour * 60 + ap.minute : null;
      const tolMin = Number(env.CONFIRM_LATE_TOLERANCE_MIN) || 10;
      if (confirmKind) {
        await handleBookedReminderReply(env, msg, confirmKind, booking, firstPhone);
      } else if (arrivalWithinTolerance(msg.text, apptMin, tolMin)) {
        // Назвал время прихода в пределах допуска опоздания → подтверждение.
        await handleBookedReminderReply(env, msg, 'yes', booking, firstPhone);
      } else if (isPoliteClosing(msg.text)) {
        // «Спасибо» / 🙏 — вежливое закрытие, БЕЗ передачи менеджеру.
        await sendMessage(env, msg, 'Будем рады видеть вас! 🌷');
        console.log(`booked client polite-closing ${tag}`);
      } else if (isQuestionOrRequest(msg.text)) {
        await sendMessage(env, msg,
          'Вы уже записаны к нам 🌷 Передаю администратору — он(а) свяжется и поможет с вашей записью.');
        if (msg.userId) {
          await env.BOT_KV.put(`op:${msg.userId}`, '1', { expirationTtl: OPERATOR_PAUSE_TTL });
        }
        console.log(`booked client question ${tag} -> handoff`);
      } else {
        // Приветствие / неясное — мягко переспрашиваем; один re-prompt, дальше → менеджер.
        const rk = `confirm_reprompt:${msg.userId}`;
        if (await env.BOT_KV.get(rk)) {
          await sendMessage(env, msg,
            'Вы уже записаны к нам 🌷 Передаю администратору — он(а) свяжется и поможет.');
          if (msg.userId) await env.BOT_KV.put(`op:${msg.userId}`, '1', { expirationTtl: OPERATOR_PAUSE_TTL });
        } else {
          await env.BOT_KV.put(rk, '1', { expirationTtl: 7200 });
          await sendMessage(env, msg, 'Здравствуйте! 🌷 Подтверждаете запись — придёте?');
        }
      }
      return;
    }
  }

  // Голосовое не распозналось, чат ведёт бот (все проверки принадлежности
  // выше пройдены) — честно просим текст. В Claude placeholder не отправляем.
  if (voiceFailed) {
    const ok = await sendMessage(env, msg,
      'Простите, не получилось расслышать голосовое 🙈 Напишите, пожалуйста, текстом — сразу отвечу.');
    if (ok) await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });
    return;
  }

  const contextHistory = appendTurn(histBefore, 'user', msg.text);

  // Слоты в промпт больше НЕ подмешиваем: бот не показывает временные окна.
  // Но подмешиваем доступность авто-записи СЕЙЧАС: только тогда Claude эмитит
  // OFFER_SLOTS (иначе ведёт обычный КЭВ). См. блок АВТО-ЗАПИСЬ в SYSTEM_PROMPT.
  const reply = await callClaude(env, contextHistory,
    buildServiceNote(kevPending, kevMissing, autobookEnabled(env, almatyNow())));

  // Если Claude недоступен — НЕ молчим: мягкий ответ + handoff менеджеру.
  let clientText;
  let booking = null;
  let handoff = null;
  let claudeFailed = false;
  let autobooked = false;
  if (reply) {
    const parsed = parseControlTags(reply);
    clientText = parsed.cleanText || 'Спасибо за сообщение! 🌸 Передаю вас менеджеру.';
    booking = parsed.booking;
    handoff = parsed.handoff;

    // Авто-запись на консультацию (OFFER_SLOTS/BOOK_CONSULT). BOOK_CONSULT —
    // легитимное продолжение, НЕ гасится при kev_pending (блокер #7); OFFER_SLOTS
    // и BOOKING_JSON гасятся как раньше. handleAutoBook сам решает гейты/фоллбэк;
    // при handled=true он подменяет текст клиенту и (при успехе) создаёт запись.
    if (parsed.bookConsult || parsed.offerSlots) {
      try {
        const ab = await handleAutoBook(env, msg, parsed, kevPending, parsed.cleanText);
        if (ab && ab.handled) {
          clientText = ab.clientText || clientText;
          if (ab.handoff) handoff = ab.handoff;
          if (ab.autobooked) autobooked = true;
          booking = null; // авто-флоу сам поставил карточку/решил фоллбэк
        }
      } catch (e) {
        console.error('handleAutoBook failed:', e && e.message);
        // фоллбэк: идём обычным КЭВ (booking/handoff из тегов, если были)
      }
    }
  } else {
    claudeFailed = true;
    clientText = 'Спасибо за сообщение! 🌸 Сейчас передам вас менеджеру — '
      + 'он(а) свяжется с вами в ближайшее время.';
    handoff = 'bot_unavailable';
  }

  // После состоявшегося КЭВ повторные BOOKING-теги игнорируем (карточка уже у
  // менеджера). Запрос изменения/отмены Claude отдаёт HANDOFF'ом — он пройдёт.
  // (Авто-запись BOOK_CONSULT выше kev_pending НЕ гасит — это отдельная ветка.)
  if (booking && kevPending) {
    console.log(`booking suppressed (kev already pending) ${tag}`);
    booking = null;
  }

  // Валидация КЭВ: тег без обязательных полей НЕ закрывает диалог — бот
  // игнорирует тег, запоминает недостающее (kev_missing) и добирает дальше.
  let bookingMissing = null;
  if (booking) {
    const v = validateBooking(booking);
    if (v.ok) {
      booking.phone = v.phone; // нормализованный 7XXXXXXXXXX
    } else {
      bookingMissing = v.missing;
      console.log(`booking incomplete ${tag}: ${v.missing.join('; ')} — добор`);
      booking = null;
    }
  }

  // Ответ клиенту. Если не доставлено — не помечаем seen и не сохраняем
  // историю: остаётся шанс на повторную обработку.
  const sent = await sendMessage(env, msg, clientText);
  if (!sent) {
    console.error(`reply not delivered ${tag}`);
    return;
  }

  await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });

  // Память добора: каких полей КЭВ не хватило в этом ходе (подмешается в
  // следующий запрос к Claude). Полный валидный BOOKING очищает её в handleBooking.
  if (bookingMissing) {
    await env.BOT_KV.put(`kev_missing:${msg.userId}`, JSON.stringify({
      missing: bookingMissing,
      at: Date.now(),
      channelId: msg.channelId,
      channelUuid: msg.channelUuid,
    }), { expirationTtl: KEV_MISSING_TTL });
  }

  // История: перечитываем свежую копию — параллельный вебхук того же клиента
  // мог записать раньше; берём более длинную, чтобы не затереть чужой ход.
  const histFresh = (await env.BOT_KV.get(histKey, { type: 'json' })) || [];
  const base = histFresh.length > baseLen ? histFresh : histBefore;
  let merged = appendTurn(base, 'user', msg.text);
  merged = appendTurn(merged, 'assistant', clientText);
  await env.BOT_KV.put(histKey, JSON.stringify(merged.slice(-HISTORY_LIMIT)),
    { expirationTtl: HISTORY_TTL });

  if (handoff) await handleHandoff(env, msg, handoff);
  if (booking) await handleBooking(env, msg, booking);

  console.log(`done ${tag} booking=${!!booking} handoff=${handoff || '-'}`
    + `${autobooked ? ' AUTO-BOOKED' : ''}`
    + `${bookingMissing ? ` missing=${bookingMissing.length}` : ''}`
    + `${kevPending ? ' kev-pending' : ''}${claudeFailed ? ' claude-fail' : ''}`);
}

// Служебная заметка для Claude (клиент её не видит, в KV-историю не пишется):
// контекст «КЭВ уже состоялся» / «каких полей не хватает» / «авто-запись доступна».
// autobookAvailable — авто-запись реально включена СЕЙЧАС (kill-switch + allowlist
// + ночь): только тогда Claude эмитит OFFER_SLOTS, иначе ведёт обычный КЭВ.
function buildServiceNote(kevPending, kevMissing, autobookAvailable) {
  if (kevPending) {
    const what = [kevPending.service, kevPending.day, kevPending.interval]
      .filter(Boolean).join(', ');
    return '[СЛУЖЕБНОЕ, КЛИЕНТ ЭТОГО НЕ ВИДИТ: заявка этого клиента УЖЕ передана '
      + `администратору${what ? ` (${what})` : ''}. Отвечай на уточняющие вопросы по сути. `
      + 'Заявку заново НЕ собирай, теги BOOKING_JSON/BOOKING/OFFER_SLOTS НЕ ставь. По '
      + 'вопросам времени и записи: «администратор свяжется и подтвердит». Если клиент '
      + 'хочет ИЗМЕНИТЬ или ОТМЕНИТЬ договорённость — поставь [[HANDOFF | изменение заявки]].]';
  }
  const parts = [];
  if (autobookAvailable) {
    parts.push('АВТО-ЗАПИСЬ ДОСТУПНА СЕЙЧАС: когда клиент готов прийти на консультацию '
      + '(есть имя И фамилия, ответ по противопоказаниям, согласие) — ставь [[OFFER_SLOTS|{...}]] '
      + 'ВМЕСТО вопроса про день/время и вместо BOOKING_JSON. Система сама покажет реальные '
      + 'окна. Время НЕ называй.');
  } else {
    parts.push('АВТО-ЗАПИСЬ СЕЙЧАС НЕДОСТУПНА: OFFER_SLOTS/BOOK_CONSULT НЕ ставь, '
      + 'закрывай обычным путём — день+интервал словами и BOOKING_JSON.');
  }
  if (kevMissing && Array.isArray(kevMissing.missing) && kevMissing.missing.length) {
    parts.push('Для заявки ещё не хватает: ' + kevMissing.missing.join(', ')
      + '. Уточни недостающее естественно (по одному вопросу за сообщение).');
  }
  return parts.length ? `[СЛУЖЕБНОЕ, КЛИЕНТ ЭТОГО НЕ ВИДИТ: ${parts.join(' ')}]` : '';
}

