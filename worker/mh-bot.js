// ── Парсинг вебхука message.help ────────────────────────────────────────────
// Тело вебхука: { action: "channel.message.created", payload: ChannelMessage }.
function parseWebhook(body) {
  if (!body || body.action !== 'channel.message.created' || !body.payload) return null;
  const p = body.payload;
  return {
    messageId: p.id,
    userId: p.user_id,
    channelId: p.channel_id,
    text: (p.message || '').trim(),
    messageType: p.message_type || 'text',
    destination: p.destination || '',
    createdAt: p.created_at || '',
  };
}

// ── Обработка одного входящего сообщения ───────────────────────────────────
async function processMessage(msg, env) {
  const tag = `u${msg.userId}`;

  // Резолвим канал из входящего: проектный вебхук message.help ловит сообщения
  // со ВСЕХ каналов проекта, но мы обслуживаем только те, что в MH_CHANNELS.
  // Незнакомый канал (Instagram и т.п.) — молча скипаем.
  const channelUuid = resolveChannelUuid(env, msg.channelId);
  if (!channelUuid) {
    console.log(`unknown channel ${msg.channelId}, skip ${tag}`);
    return;
  }
  msg.channelUuid = channelUuid;

  // Эхо-защита: сообщение, отправленное самим ботом, message.help может вернуть
  // обратно вебхуком. Свои id мы помечаем при отправке — такие пропускаем.
  if (msg.messageId && await env.BOT_KV.get(`sent:${msg.messageId}`)) return;

  // Сотрудник подключился к чату — бот немедленно умолкает и больше не
  // перебивает. Сигналы message.help (подтверждено на проде в pulse-боте):
  //   from_whatsapp / from_instagram / from_operator / from_* — ИСХОДЯЩИЙ
  //     ответ человека через канал (раньше ловили только from_operator —
  //     реальные ответы менеджеров приходят как from_<канал>, и днём бот
  //     перебивал бы живой диалог);
  //   contact_in_work — сотрудник взял контакт в работу (ловим подключение
  //     ещё до того, как он что-то напишет).
  // Свои сообщения отсеяны эхо-защитой выше; на случай гонки «вебхук обогнал
  // запись sent:» — перепроверяем пометку после паузы, чтобы бот не заглушил
  // сам себя собственным эхом.
  const isOutboundEcho = typeof msg.destination === 'string'
    && msg.destination !== 'from' && msg.destination.startsWith('from_');
  if (isOutboundEcho || msg.destination === 'contact_in_work') {
    if (isOutboundEcho && msg.messageId) {
      await sleep(1500);
      if (await env.BOT_KV.get(`sent:${msg.messageId}`)) return; // своё эхо
    }
    if (msg.userId) {
      await env.BOT_KV.put(`op:${msg.userId}`, '1', { expirationTtl: OPERATOR_PAUSE_TTL });
      console.log(`operator joined -> bot paused ${tag} (${msg.destination})`);
    }
    return;
  }

  // Обрабатываем ТОЛЬКО входящие текстовые сообщения от клиента.
  // destination=from — «От пользователя». Всё прочее (to, notice_*, ai,
  // comment, altegio_*, ...) — исходящее/служебное/автоматическое, не наше.
  if (msg.destination !== 'from') return;
  if (msg.messageType !== 'text') return;
  if (!msg.text || !msg.userId) return;

  // Дедуп — message.help может повторить доставку вебхука. Делаем ДО
  // confirm_pending, чтобы не среагировать дважды на ответ «Да/Нет».
  const seenKey = `seen:${msg.messageId}`;
  if (await env.BOT_KV.get(seenKey)) return;

  // Ответ клиента на подтверждение записи — НЕЗАВИСИМО от часа суток.
  // Цепочка должна быть доведена в любом случае: «Да» → attendance=2,
  // «Нет» → передача менеджеру, любой другой ответ («можно перенести?»,
  // «во сколько было?», «не уверена пока») → ТАКЖЕ передача менеджеру.
  // Раньше «другой» ответ проваливался в Claude-flow, а днём бот его
  // скипал по night-window → клиент оставался без ответа.
  const pendingRaw = await env.BOT_KV.get(`confirm_pending:user:${msg.userId}`);
  if (pendingRaw) {
    let pending = null;
    try { pending = JSON.parse(pendingRaw); } catch (_) { pending = null; }
    const kind = classifyConfirmationResponse(msg.text);
    await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });
    if (kind === 'yes' || kind === 'no') {
      await handleConfirmationResponse(env, msg, kind, pending);
    } else {
      await handleConfirmationFollowUp(env, msg, pending);
    }
    return;
  }

  // Ответ клиента на engage-сообщение рассылки акций. Так же круглосуточно.
  // «Да/+/интересно/расскажите» → отправляем полный шаблон акций (шаг 2).
  // «Нет/не нужно/отпишите» → opt-out на 365 дней + вежливый ответ.
  // Длинный/непонятный ответ → передаём менеджеру (он лучше отработает
  // вопросы про цену конкретной программы и т.п.).
  const engageRaw = await env.BOT_KV.get(`broadcast_engage_pending:user:${msg.userId}`);
  if (engageRaw) {
    let engage = null;
    try { engage = JSON.parse(engageRaw); } catch (_) { engage = null; }
    const kind = classifyConfirmationResponse(msg.text);
    await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });
    if (kind === 'yes') {
      await handleBroadcastEngageYes(env, msg, engage);
    } else if (kind === 'no') {
      await handleBroadcastEngageNo(env, msg, engage);
    } else {
      await handleBroadcastEngageOther(env, msg, engage);
    }
    return;
  }

  // Окно лид-диалога: с 12.06.2026 BOT_HOUR_* = 0..24 (круглосуточно), бот
  // отвечает и днём — менеджер «выигрывает» чат первым же своим сообщением
  // (op:-пауза выше). Эхо-защита, операторская пауза и обработка ответа на
  // confirmation работают всегда, независимо от окна.
  const hour = almatyNow().hour;
  const inWindow = BOT_HOUR_START < BOT_HOUR_END
    ? (hour >= BOT_HOUR_START && hour < BOT_HOUR_END)
    : (hour >= BOT_HOUR_START || hour < BOT_HOUR_END);
  if (!inWindow) {
    console.log(`outside bot hours (h=${hour}, window=${BOT_HOUR_START}-${BOT_HOUR_END}), skip ${tag}`);
    return;
  }

  // Чат уже ведёт человек (сотрудник подключился, или бот ранее сделал
  // handoff) — бот не вмешивается.
  if (await env.BOT_KV.get(`op:${msg.userId}`)) {
    console.log(`paused, human owns ${tag}`);
    return;
  }

  // КЭВ уже состоялся (заявка передана менеджеру, kev_pending активен 48ч):
  // бот продолжает отвечать на уточнения («а парковка есть?»), но заявку
  // заново не собирает и ПОВТОРНЫХ карточек не создаёт.
  let kevPending = null;
  const kevPendingRaw = await env.BOT_KV.get(`kev_pending:${msg.userId}`);
  if (kevPendingRaw) {
    try { kevPending = JSON.parse(kevPendingRaw); } catch (_) { kevPending = {}; }
  }

  // Прерванный добор полей КЭВ с прошлого хода — напомним Claude, чего не хватает.
  let kevMissing = null;
  if (!kevPending) {
    const kevMissingRaw = await env.BOT_KV.get(`kev_missing:${msg.userId}`);
    if (kevMissingRaw) {
      try { kevMissing = JSON.parse(kevMissingRaw); } catch (_) { kevMissing = null; }
    }
  }

  // История диалога (baseLen — для защиты от гонки при записи).
  const histKey = `hist:${msg.userId}`;
  const histBefore = (await env.BOT_KV.get(histKey, { type: 'json' })) || [];
  const baseLen = histBefore.length;

  // Первый контакт бота с этим клиентом (истории ещё нет) — два гейта:
  if (baseLen === 0) {
    // 1) В этом чате сегодня-вчера уже отвечал ЧЕЛОВЕК (по журналу событий
    //    pulse-бота) — чат менеджера, бот не влезает. Без этого при дневном
    //    режиме бот перебивал бы живые диалоги, начатые до его включения.
    if (await humanOwnsDialog(env, msg.userId)) {
      await env.BOT_KV.put(`op:${msg.userId}`, '1', { expirationTtl: OPERATOR_PAUSE_TTL });
      console.log(`skip: human already in dialog ${tag} -> paused`);
      return;
    }
    // 2) Гейт «только новые лиды»: действующих клиентов студии бот не трогает.
    const cls = await classifyContact(msg, env);
    if (cls === 'existing') {
      console.log(`skip existing client ${tag}`);
      return;
    }
  }

  const contextHistory = appendTurn(histBefore, 'user', msg.text);

  // Слоты в промпт больше НЕ подмешиваем: бот не показывает временные окна,
  // выбор времени делает менеджер. См. блок «ВРЕМЯ И РАСПИСАНИЕ» в SYSTEM_PROMPT.
  const reply = await callClaude(env, contextHistory,
    buildServiceNote(kevPending, kevMissing));

  // Если Claude недоступен — НЕ молчим: мягкий ответ + handoff менеджеру.
  let clientText;
  let booking = null;
  let handoff = null;
  let claudeFailed = false;
  if (reply) {
    const parsed = parseControlTags(reply);
    clientText = parsed.cleanText || 'Спасибо за сообщение! 🌸 Передаю вас менеджеру.';
    booking = parsed.booking;
    handoff = parsed.handoff;
  } else {
    claudeFailed = true;
    clientText = 'Спасибо за сообщение! 🌸 Сейчас передам вас менеджеру — '
      + 'он(а) свяжется с вами в ближайшее время.';
    handoff = 'bot_unavailable';
  }

  // После состоявшегося КЭВ повторные BOOKING-теги игнорируем (карточка уже у
  // менеджера). Запрос изменения/отмены Claude отдаёт HANDOFF'ом — он пройдёт.
  if (booking && kevPending) {
    console.log(`booking suppressed (kev already pending) ${tag}`);
    booking = null;
  }

  // Валидация КЭВ: тег без обязательных полей НЕ закрывает диалог — бот
  // игнорирует тег, запоминает недостающее (kev_missing) и добирает дальше.
  let bookingMissing = null;
  if (booking) {
    const v = validateBooking(booking);
    if (v.ok) {
      booking.phone = v.phone; // нормализованный 7XXXXXXXXXX
    } else {
      bookingMissing = v.missing;
      console.log(`booking incomplete ${tag}: ${v.missing.join('; ')} — добор`);
      booking = null;
    }
  }

  // Ответ клиенту. Если не доставлено — не помечаем seen и не сохраняем
  // историю: остаётся шанс на повторную обработку.
  const sent = await sendMessage(env, msg, clientText);
  if (!sent) {
    console.error(`reply not delivered ${tag}`);
    return;
  }

  await env.BOT_KV.put(seenKey, '1', { expirationTtl: DEDUP_TTL });

  // Память добора: каких полей КЭВ не хватило в этом ходе (подмешается в
  // следующий запрос к Claude). Полный валидный BOOKING очищает её в handleBooking.
  if (bookingMissing) {
    await env.BOT_KV.put(`kev_missing:${msg.userId}`, JSON.stringify({
      missing: bookingMissing,
      at: Date.now(),
      channelId: msg.channelId,
      channelUuid: msg.channelUuid,
    }), { expirationTtl: KEV_MISSING_TTL });
  }

  // История: перечитываем свежую копию — параллельный вебхук того же клиента
  // мог записать раньше; берём более длинную, чтобы не затереть чужой ход.
  const histFresh = (await env.BOT_KV.get(histKey, { type: 'json' })) || [];
  const base = histFresh.length > baseLen ? histFresh : histBefore;
  let merged = appendTurn(base, 'user', msg.text);
  merged = appendTurn(merged, 'assistant', clientText);
  await env.BOT_KV.put(histKey, JSON.stringify(merged.slice(-HISTORY_LIMIT)),
    { expirationTtl: HISTORY_TTL });

  if (handoff) await handleHandoff(env, msg, handoff);
  if (booking) await handleBooking(env, msg, booking);

  console.log(`done ${tag} booking=${!!booking} handoff=${handoff || '-'}`
    + `${bookingMissing ? ` missing=${bookingMissing.length}` : ''}`
    + `${kevPending ? ' kev-pending' : ''}${claudeFailed ? ' claude-fail' : ''}`);
}

// Служебная заметка для Claude (клиент её не видит, в KV-историю не пишется):
// контекст «КЭВ уже состоялся» либо «каких полей заявки не хватает».
function buildServiceNote(kevPending, kevMissing) {
  if (kevPending) {
    const what = [kevPending.service, kevPending.day, kevPending.interval]
      .filter(Boolean).join(', ');
    return '[СЛУЖЕБНОЕ, КЛИЕНТ ЭТОГО НЕ ВИДИТ: заявка этого клиента УЖЕ передана '
      + `администратору${what ? ` (${what})` : ''}. Отвечай на уточняющие вопросы по сути. `
      + 'Заявку заново НЕ собирай, теги BOOKING_JSON/BOOKING НЕ ставь. По вопросам '
      + 'времени и записи: «администратор свяжется и подтвердит». Если клиент хочет '
      + 'ИЗМЕНИТЬ или ОТМЕНИТЬ договорённость — поставь [[HANDOFF | изменение заявки]].]';
  }
  if (kevMissing && Array.isArray(kevMissing.missing) && kevMissing.missing.length) {
    return '[СЛУЖЕБНОЕ, КЛИЕНТ ЭТОГО НЕ ВИДИТ: для заявки ещё не хватает: '
      + kevMissing.missing.join(', ')
      + '. Уточни недостающее естественно (по одному вопросу за сообщение) и поставь '
      + 'полный BOOKING_JSON, когда всё соберёшь.]';
  }
  return '';
}

// ── Гейт: новый лид или действующий клиент ─────────────────────────────────
// Возвращает 'new' | 'existing'. Действующий клиент = есть история визитов в
// Altegio. Бот Altegio только ЧИТАЕТ.
// Altegio-проверка опциональна: без токенов гейт опирается на остальные слои
// (фильтр destination, пауза оператора, распознавание в промпте). При любой
// ошибке/неопределённости → 'new': лид не блокируем, действующего клиента
// подстрахуют пауза оператора и промпт ([[HANDOFF | existing_client]]).
async function classifyContact(msg, env) {
  if (!env.ALTEGIO_PARTNER_TOKEN || !env.ALTEGIO_USER_TOKEN || !env.ALTEGIO_COMPANY_ID) {
    return 'new';
  }
  try {
    const phone = await getContactPhone(env, msg);
    if (!phone) return 'new';
    return (await altegioHasVisitHistory(env, phone)) ? 'existing' : 'new';
  } catch (e) {
    console.error('classifyContact error:', e && e.message);
    return 'new';
  }
}

// Отвечал ли в этом диалоге сегодня-вчера ЧЕЛОВЕК. Источник — журнал событий
// mm-pulse-bot (binding PULSE_KV, читаем read-only по соглашению): pulse пишет
// в events:{YYYY-MM-DD} все сообщения проекта; исходящие самого mh-bot там
// помечены bot:true и человеком не считаются. Нет binding'а / журнал пуст —
// false (бот работает как раньше). Проверяется один раз — на первом контакте
// бота с клиентом (дальше ownership ведут op:-пауза и сигналы from_*).
async function humanOwnsDialog(env, userId) {
  if (!env.PULSE_KV || typeof env.PULSE_KV.get !== 'function') return false;
  const now = almatyNow();
  for (const ymd of [now.ymd, ymdDaysAhead(now, -1)]) {
    let bucket = null;
    try {
      bucket = await env.PULSE_KV.get(`events:${ymd}`, { type: 'json' });
    } catch (e) {
      console.error('humanOwnsDialog read:', e && e.message);
      return false; // не смогли прочитать — не блокируем бота
    }
    if (!Array.isArray(bucket)) continue;
    for (const e of bucket) {
      if (e && String(e.dialog_id) === String(userId)
        && e.direction === 'operator' && !e.bot) return true;
    }
  }
  return false;
}

// Телефон клиента по user_id из message.help. Используем uuid того канала,
// откуда пришёл вебхук (msg.channelUuid).
async function getContactPhone(env, msg) {
  const token = await getMhToken(env);
  if (!token) return null;
  const url = `${MH_API}/app/projects/${env.MH_PROJECT_ID}`
    + `/channels/${msg.channelUuid}/users/${msg.userId}`;
  let res;
  try {
    res = await fetch(url, { headers: { Authorization: `Bearer ${token}` } });
  } catch (e) {
    console.error('mh get-user error:', e && e.message);
    return null;
  }
  if (!res.ok) {
    console.error('mh get-user:', res.status);
    return null;
  }
  const data = await res.json().catch(() => null);
  const u = (data && data.data) || data || {};
  const raw = u.phone || u.contact_phone || (u.contact && u.contact.phone) || '';
  const digits = String(raw).replace(/\D/g, '');
  return digits.length >= 10 ? digits : null;
}

// Есть ли у телефона история визитов в Altegio (= действующий клиент).
// Бот только читает.
async function altegioHasVisitHistory(env, phone) {
  const url = `${ALTEGIO_API}/company/${env.ALTEGIO_COMPANY_ID}/clients/search`;
  let res;
  try {
    res = await fetch(url, {
      method: 'POST',
      headers: altegioHeaders(env),
      body: JSON.stringify({
        page: 1,
        page_size: 5,
        fields: ['id', 'phone', 'visit_count'],
        filters: [{ type: 'quick_search', state: phone }],
      }),
    });
  } catch (e) {
    console.error('altegio search error:', e && e.message);
    return false;
  }
  if (!res.ok) {
    console.error('altegio search:', res.status);
    return false;
  }
  const data = await res.json().catch(() => null);
  const list = (data && data.data) || [];
  if (!Array.isArray(list) || !list.length) return false;
  // Действующий клиент — тот, кто уже был в студии (есть визиты).
  return list.some((c) => Number(c && c.visit_count) > 0);
}

// Заголовки Altegio API (двойной токен: партнёр + пользователь).
function altegioHeaders(env) {
  return {
    Authorization: `Bearer ${env.ALTEGIO_PARTNER_TOKEN}, User ${env.ALTEGIO_USER_TOKEN}`,
    Accept: 'application/vnd.api.v2+json',
    'Content-Type': 'application/json',
  };
}

// ── История: чередование ролей, склейка подряд идущих сообщений одной роли ──
function appendTurn(history, role, content) {
  const h = history.slice();
  const last = h[h.length - 1];
  if (last && last.role === role) {
    h[h.length - 1] = { role, content: `${last.content}\n${content}` };
  } else {
    h.push({ role, content });
  }
  return h;
}

// ── Вызов Claude API (raw fetch, prompt caching, retry) ─────────────────────
// serviceNote (опц.) — служебный контекст хода («КЭВ уже передан» / «не хватает
// полей»), добавляется ТОЛЬКО в последнее user-сообщение запроса; в KV-историю
// не попадает, prompt cache системного префикса не ломает.
async function callClaude(env, history, serviceNote) {
  // Слоты в промпт НЕ подмешиваем — бот не показывает временные слоты.
  // НО подмешиваем ТЕКУЩУЮ ДАТУ (Almaty) в последнее user-сообщение —
  // нужна для логики «акция действует до 15.06.2026». Подмешиваем только
  // в последнее сообщение, чтобы системный префикс и старые ходы остались
  // стабильными для prompt cache.
  const apiMessages = history.map((m) => ({ role: m.role, content: m.content }));
  // Дата — для логики акций, время — для обещаний клиенту («администратор
  // свяжется в ближайшее время» днём vs «напишет утром» ночью), см. раздел
  // «ВРЕМЯ СУТОК» в SYSTEM_PROMPT.
  const nowA = almatyNow();
  const nowStr = `${nowA.ymd} ${String(nowA.hour).padStart(2, '0')}:${String(nowA.minute).padStart(2, '0')}`;
  for (let i = apiMessages.length - 1; i >= 0; i--) {
    if (apiMessages[i].role === 'user') {
      apiMessages[i] = {
        role: 'user',
        content: `ТЕКУЩАЯ ДАТА И ВРЕМЯ (Алматы): ${nowStr}\n\n${apiMessages[i].content}`
          + (serviceNote ? `\n\n${serviceNote}` : ''),
      };
      break;
    }
  }

  const payload = {
    model: env.ANTHROPIC_MODEL || DEFAULT_MODEL,
    max_tokens: 1024,
    temperature: BOT_TEMPERATURE,
    system: [{ type: 'text', text: SYSTEM_PROMPT, cache_control: { type: 'ephemeral' } }],
    messages: apiMessages,
  };

  for (let attempt = 0; attempt < 3; attempt++) {
    let res;
    try {
      res = await fetch(ANTHROPIC_URL, {
        method: 'POST',
        headers: {
          'x-api-key': env.ANTHROPIC_API_KEY,
          'anthropic-version': ANTHROPIC_VERSION,
          'content-type': 'application/json',
        },
        body: JSON.stringify(payload),
      });
    } catch (e) {
      console.error('Claude fetch error:', e && e.message);
      await sleep(500 * (attempt + 1));
      continue;
    }

    if (res.ok) {
      const data = await res.json();
      const u = data.usage || {};
      console.log(`claude ok cache_read=${u.cache_read_input_tokens || 0} in=${u.input_tokens || 0} out=${u.output_tokens || 0}`);
      if (data.stop_reason === 'refusal') {
        console.error('Claude refusal — отдаём на менеджера');
        return '';
      }
      const textBlock = (data.content || []).find((b) => b.type === 'text');
      return textBlock ? textBlock.text.trim() : '';
    }

    // 429 / 5xx — ретраить; 4xx (кроме 429) — нет смысла
    if (res.status !== 429 && res.status < 500) {
      console.error(`Claude API ${res.status}:`, (await res.text()).slice(0, 200));
      return '';
    }
    const retryAfter = parseInt(res.headers.get('retry-after') || '0', 10);
    await sleep(retryAfter ? retryAfter * 1000 : 800 * (attempt + 1));
  }
  console.error('Claude API: retries exhausted');
  return '';
}

// ── Управляющие теги [[BOOKING_JSON|{...}]] / [[BOOKING|...]] / [[HANDOFF|...]] ──
// Основной формат КЭВ — BOOKING_JSON (имя/телефон/процедура/день/интервал/
// противопоказания/язык/температура). Старый позиционный [[BOOKING|a|b|c|d|e]]
// поддержан для обратной совместимости: его «слот» считается «день+интервал»
// одной строкой (поле day, legacy=true).
function parseControlTags(text) {
  let booking = null;
  let handoff = null;

  // Новый формат: [[BOOKING_JSON|{...}]] (JSON одной строкой).
  const jsonRe = /\[\[\s*BOOKING_JSON\s*\|\s*(\{[\s\S]*?\})\s*\]\]/gi;
  let jm;
  while ((jm = jsonRe.exec(text)) !== null) {
    try {
      const o = JSON.parse(jm[1]);
      booking = {
        name: String(o.name || '').trim(),
        phone: String(o.phone || '').replace(/\D/g, ''),
        service: String(o.service || '').trim(),
        day: String(o.day || '').trim(),
        interval: String(o.interval || '').trim(),
        contraindications: String(o.contra || o.contraindications || '').trim(),
        lang: (String(o.lang || '').trim().toLowerCase() === 'kz') ? 'kz' : 'ru',
        temp: (String(o.temp || '').trim().toLowerCase() === 'hot') ? 'hot' : 'warm',
      };
    } catch (e) {
      // Битый JSON = тега нет: диалог продолжится, Claude обычно чинит сам.
      console.error('BOOKING_JSON parse error:', e && e.message);
    }
  }

  // Старый формат + HANDOFF.
  const re = /\[\[\s*(BOOKING|HANDOFF)\s*\|([^\]]*)\]\]/gi;
  let match;
  while ((match = re.exec(text)) !== null) {
    const kind = match[1].toUpperCase();
    const payload = match[2].trim();
    if (kind === 'BOOKING') {
      if (!booking) { // BOOKING_JSON приоритетнее, если Claude поставил оба
        const p = payload.split('|').map((s) => s.trim());
        booking = { name: p[0] || '', phone: (p[1] || '').replace(/\D/g, ''),
          service: p[2] || '', day: p[3] || '', interval: '',
          contraindications: p[4] || '', lang: 'ru', temp: 'warm', legacy: true };
      }
    } else {
      handoff = payload || 'general';
    }
  }

  const cleanText = text.replace(jsonRe, '').replace(re, '')
    .replace(/\n{3,}/g, '\n\n').trim();
  return { cleanText, booking, handoff };
}

// Валидация карточки КЭВ. ok=false → тег не закрывает диалог, missing подмешается
// в следующий запрос Claude. Для легаси-формата day («слот») засчитывается как
// день+интервал. Возвращает нормализованный телефон (7XXXXXXXXXX).
function validateBooking(b) {
  const missing = [];
  if (!b.name) missing.push('имя клиента');
  const ph = normalizePhone(b.phone);
  if (!ph || ph.length !== 11 || ph[0] !== '7') missing.push('телефон (11 цифр, формат 7…)');
  if (!b.service) missing.push('процедура/зона');
  if (b.legacy) {
    if (!b.day) missing.push('желаемый день и время');
  } else {
    if (!b.day) missing.push('желаемый день');
    if (!b.interval) missing.push('интервал времени (или пожелание клиента)');
  }
  if (!b.contraindications) missing.push('ответ по противопоказаниям (или «нет»)');
  return { ok: !missing.length, missing, phone: ph };
}

// (УДАЛЕНО 05.06.2026) buildSlotsBlock / getAltegioSlots / buildTemplateSlots
// Бот больше не показывает свободные слоты — точное расписание клиенту не
// выдаёт. Функция бота: сбор заявки (имя/телефон/общее предпочтение) и
// передача менеджеру, который сам подберёт слот и оформит запись.

// ── Токен message.help (логин + кэш в KV) ──────────────────────────────────
// Токен живёт expires_in секунд; кэшируем с запасом 5 минут.
async function getMhToken(env, force) {
  if (!force) {
    const cached = await env.BOT_KV.get(TOKEN_KEY);
    if (cached) return cached;
  }
  let res;
  try {
    res = await fetch(`${MH_API}/app/user/login`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ login: env.MH_LOGIN, password: env.MH_PASSWORD }),
    });
  } catch (e) {
    console.error('mh login fetch error:', e && e.message);
    return null;
  }
  if (!res.ok) {
    console.error('mh login failed:', res.status);
    return null;
  }
  const data = await res.json().catch(() => null);
  const token = data && data.data && data.data.access_token;
  if (!token) {
    console.error('mh login: no access_token in response');
    return null;
  }
  const expires = (data.data.expires_in && parseInt(data.data.expires_in, 10)) || 3600;
  await env.BOT_KV.put(TOKEN_KEY, token, { expirationTtl: Math.max(60, expires - 300) });
  return token;
}

// ── Отправка ответа клиенту через message.help ─────────────────────────────
// send_message принимает multipart/form-data; destination=from_operator —
// сообщение уходит клиенту как ответ оператора.
// Возвращает true при успешной доставке, false — если доставить не удалось.
async function sendMessage(env, msg, text) {
  for (let attempt = 0; attempt < 3; attempt++) {
    const token = await getMhToken(env, attempt > 0);  // на ретрае — свежий токен
    if (!token) {
      await sleep(500 * (attempt + 1));
      continue;
    }
    const url = `${MH_API}/app/projects/${env.MH_PROJECT_ID}`
      + `/channels/${msg.channelUuid}/send_message/${msg.userId}`;
    let res;
    try {
      const form = new FormData();
      form.append('text', text);
      form.append('destination', 'from_operator');
      res = await fetch(url, {
        method: 'POST',
        headers: { Authorization: `Bearer ${token}` },
        body: form,
      });
    } catch (e) {
      console.error('mh send error:', e && e.message);
      await sleep(500 * (attempt + 1));
      continue;
    }

    if (res.ok) {
      // Помечаем id своего сообщения — чтобы не среагировать на его эхо.
      const data = await res.json().catch(() => null);
      const sentId = data && data.data && data.data.id;
      if (sentId) {
        await env.BOT_KV.put(`sent:${sentId}`, '1', { expirationTtl: SENT_TTL });
      }
      return true;
    }
    if (res.status === 401) {
      // токен протух раньше TTL — сбросить кэш, на следующем attempt перелогин
      await env.BOT_KV.delete(TOKEN_KEY);
      continue;
    }
    if (res.status !== 429 && res.status < 500) {
      console.error(`mh send ${res.status}:`, (await res.text()).slice(0, 200));
      return false;
    }
    const retryAfter = parseInt(res.headers.get('retry-after') || '0', 10);
    await sleep(retryAfter ? retryAfter * 1000 : 600 * (attempt + 1));
  }
  console.error('mh send: retries exhausted');
  return false;
}

