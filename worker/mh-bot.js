// РАССЫЛКА (BROADCAST)
// Активируется через env.BROADCAST_ACTIVE='1'. Шлёт акции по базе активных
// клиентов Altegio строго через WA2 (channel 20916). Темплейты ротируются
// по часу. Полностью отдельный поток от confirmation: свой dedup, свой
// часовой счётчик, свой sleep.
// ════════════════════════════════════════════════════════════════════════════

async function runBroadcastJob(env) {
  if (env.BROADCAST_ACTIVE !== '1') return;
  if (!env.MH_LOGIN || !env.MH_PASSWORD || !env.MH_PROJECT_ID) {
    console.log('broadcast: message.help not configured, skip');
    return;
  }
  if (!env.ALTEGIO_PARTNER_TOKEN || !env.ALTEGIO_USER_TOKEN
    || !env.ALTEGIO_COMPANY_ID) {
    console.log('broadcast: altegio not configured, skip');
    return;
  }

  const now = almatyNow();
  if (now.hour >= BROADCAST_END_HOUR) {
    console.log(`broadcast: ended (h=${now.hour} >= ${BROADCAST_END_HOUR})`);
    return;
  }
  if (now.hour < CONFIRM_HOUR_START) {
    console.log(`broadcast: before start (h=${now.hour})`);
    return;
  }

  // startedAt — записываем в KV при первом tick'е дня
  const startedKey = `broadcast:started:${now.ymd}`;
  let startedAt = await env.BOT_KV.get(startedKey);
  if (!startedAt) {
    startedAt = new Date(now.ms).toISOString();
    await env.BOT_KV.put(startedKey, startedAt, { expirationTtl: 90000 });
    console.log(`broadcast: started at ${startedAt} (Almaty ${now.ymd} ${now.hour}:${String(now.minute).padStart(2,'0')})`);
  }
  const startedMs = new Date(startedAt).getTime();
  const hoursSinceStart = Math.floor((now.ms - startedMs) / 3600000);
  const templateIdx = ((hoursSinceStart % 3) + 3) % 3;

  // Дневной потолок — страховка под правило message.help «не более 300/день»
  const dayKey = `broadcast_day:${now.ymd}`;
  const dayUsed = Number(await env.BOT_KV.get(dayKey)) || 0;
  if (dayUsed >= BROADCAST_PER_DAY) {
    console.log(`broadcast: day cap reached (${dayUsed}/${BROADCAST_PER_DAY}) — стоп до завтра`);
    return;
  }
  // Часовой потолок 30/час
  const hourKey = `broadcast_hour:${now.ymdh}`;
  const hourUsed = Number(await env.BOT_KV.get(hourKey)) || 0;
  if (hourUsed >= BROADCAST_PER_HOUR) {
    console.log(`broadcast: hour cap reached (${hourUsed}/${BROADCAST_PER_HOUR}) at h=${now.hour}`);
    return;
  }
  const remainingThisHour = BROADCAST_PER_HOUR - hourUsed;
  const remainingToday = BROADCAST_PER_DAY - dayUsed;
  const tickQuota = Math.min(BROADCAST_TICK_MAX, remainingThisHour, remainingToday);

  // База клиентов Altegio (кеш в KV на 6ч)
  const base = await fetchBroadcastBase(env);
  if (!base || !base.length) {
    console.log('broadcast: empty base, skip');
    return;
  }

  const token = await getMhToken(env);
  if (!token) {
    console.error('broadcast: no MH token');
    return;
  }

  shuffleInPlace(base);
  // Шаг 1 (engage): короткий вопрос с открытием нового чата на WA2.
  const text = BROADCAST_ENGAGE_TEMPLATES[templateIdx];

  let sent = 0;
  let dedupSkip = 0;
  let optoutSkip = 0;
  let noContactSkip = 0;
  let pendingSkip = 0;
  let opSkip = 0;

  for (const client of base) {
    if (sent >= tickQuota) break;

    const phone = normalizePhone(client.phone);
    if (!phone) continue;

    // Чёрный список из Altegio — hard-coded (см. константу BROADCAST_BLACKLIST_PHONES)
    if (BROADCAST_BLACKLIST_PHONES.has(phone)) { optoutSkip++; continue; }
    // Уже шла рассылка этому телефону
    if (await env.BOT_KV.get(`broadcast_sent:${phone}`)) { dedupSkip++; continue; }
    // Клиент когда-то ответил «нет/отпишите» — больше не пишем
    if (await env.BOT_KV.get(`broadcast_optout:${phone}`)) { optoutSkip++; continue; }

    // ШАГ 1: ищем существующий контакт БЕЗ создания нового чата.
    // Если клиент уже писал нам — провалидируем блокировки по его userId.
    let resolved = await mhResolveContactStrict(env, token, phone,
      BROADCAST_CHANNEL_ID, BROADCAST_CHANNEL_UUID, false);

    if (resolved) {
      // Существующий контакт — проверяем блокировки
      if (await env.BOT_KV.get(`confirm_pending:user:${resolved.userId}`)) {
        pendingSkip++;
        continue;
      }
      if (await env.BOT_KV.get(`op:${resolved.userId}`)) {
        opSkip++;
        continue;
      }
      if (await env.BOT_KV.get(`broadcast_engage_pending:user:${resolved.userId}`)) {
        dedupSkip++;
        continue;
      }
    } else {
      // ОТКАЗ от need_create=true: message.help при попытке создать чат на WA2
      // игнорирует наш channel_uuid и привязывает контакт к WA1 (17222),
      // потому что у клиентов уже есть история на WA1. Наш фильтр channel_id===20916
      // не находит запись → send не делается → но триггер «Создать сделку» в
      // воронке Records Altegio уже сработал на сам факт contact_by_phone.
      // Итог: 84 пустых сделок 10.06 + 5.6% реальной отправки.
      // Решение: шлём ТОЛЬКО тем, у кого уже есть история на WA2.
      // Это соответствует правилу message.help bulk-FAQ.
      noContactSkip++;
      continue;
    }

    // Атомарная отправка с одним retry на сетевой/5xx сбой —
    // чтобы не оставлять пустой чат после успешного create.
    let ok = await mhSendDirect(env, token,
      BROADCAST_CHANNEL_UUID, resolved.userId, text);
    if (!ok) {
      await sleep(2000 + Math.floor(Math.random() * 2000));
      ok = await mhSendDirect(env, token,
        BROADCAST_CHANNEL_UUID, resolved.userId, text);
    }
    if (!ok) {
      console.error(`broadcast: send failed phone=${maskPhone(phone)} userId=${resolved.userId}`);
      continue;
    }

    sent++;
    await env.BOT_KV.put(`broadcast_sent:${phone}`, JSON.stringify({
      sentAt: new Date().toISOString(),
      templateIdx, userId: resolved.userId, step: 'engage',
    }), { expirationTtl: BROADCAST_DEDUP_TTL });
    // Pending для второго этапа: при ответе клиента (да/нет/что-то ещё)
    // processMessage заглянет сюда и поймёт что отправить.
    await env.BOT_KV.put(`broadcast_engage_pending:user:${resolved.userId}`,
      JSON.stringify({
        phone, templateIdx, sentAt: new Date().toISOString(),
      }), { expirationTtl: BROADCAST_ENGAGE_PENDING_TTL });
    await env.BOT_KV.put(hourKey, String(hourUsed + sent),
      { expirationTtl: BROADCAST_HOUR_COUNTER_TTL });
    await env.BOT_KV.put(dayKey, String(dayUsed + sent),
      { expirationTtl: 90000 });

    if (sent < tickQuota) {
      await sleep(BROADCAST_TICK_PAUSE_MIN
        + Math.floor(Math.random()
          * (BROADCAST_TICK_PAUSE_MAX - BROADCAST_TICK_PAUSE_MIN)));
    }
  }

  console.log(`broadcast engage tick: base=${base.length}, h=${now.hour}:${String(now.minute).padStart(2,'0')}, `
    + `template=${templateIdx + 1}, hour_used=${hourUsed + sent}/${BROADCAST_PER_HOUR}, `
    + `day_used=${dayUsed + sent}/${BROADCAST_PER_DAY}, this_tick=${sent}, `
    + `dedup=${dedupSkip}, optout=${optoutSkip}, no_contact=${noContactSkip}, `
    + `pending=${pendingSkip}, op=${opSkip}`);
}

// Выгрузка активной базы клиентов из Altegio с кешем в KV на BASE_CACHE_TTL.
// Берём ВСЕХ кто есть в базе с телефоном (фильтр visit_count > 0 убран
// 10.06.2026 — на WA2 база активных была охвачена ~70%, нужно расширение
// для продолжения рассылки). Источник: clients/search с пагинацией.
async function fetchBroadcastBase(env) {
  const cacheKey = `broadcast:base:${almatyNow().ymd}`;
  const cached = await env.BOT_KV.get(cacheKey, { type: 'json' });
  if (cached && Array.isArray(cached) && cached.length) return cached;

  const out = [];
  for (let page = 1; page <= 50; page++) {
    const url = `${ALTEGIO_API}/company/${env.ALTEGIO_COMPANY_ID}/clients/search`;
    let res;
    try {
      res = await fetch(url, {
        method: 'POST',
        headers: altegioHeaders(env),
        body: JSON.stringify({
          page,
          page_size: 200,
          fields: ['id', 'phone', 'name'],
          filters: [],
        }),
      });
    } catch (e) {
      console.error(`broadcast base page ${page}:`, e && e.message);
      break;
    }
    if (!res.ok) {
      console.error(`broadcast base page ${page}: HTTP ${res.status}`);
      break;
    }
    const data = await res.json().catch(() => null);
    const list = (data && data.data) || [];
    if (!list.length) break;
    for (const c of list) {
      if (!c || !c.phone) continue;
      out.push({ phone: c.phone, name: c.name });
    }
    if (list.length < 200) break;
  }

  console.log(`broadcast: base fetched ${out.length} clients`);
  await env.BOT_KV.put(cacheKey, JSON.stringify(out),
    { expirationTtl: BROADCAST_BASE_CACHE_TTL });
  return out;
}

// Строгий резолв контакта по телефону: ТОЛЬКО на канале BROADCAST_CHANNEL_ID.
// Если клиент на нём не писал — возвращает null (не открываем новый чат).
async function mhResolveContactStrict(env, token, phone,
  targetChannelId, targetChannelUuid, needCreate = false) {
  let res;
  const body = {
    phone,
    need_create: !!needCreate,
  };
  if (needCreate) body.channel_uuid = targetChannelUuid;
  try {
    res = await fetch(
      `${MH_API}/app/projects/${env.MH_PROJECT_ID}/contacts/contact_by_phone`,
      {
        method: 'POST',
        headers: { Authorization: `Bearer ${token}`,
          'content-type': 'application/json' },
        body: JSON.stringify(body),
      });
  } catch (e) {
    console.error('broadcast contact_by_phone:', e && e.message);
    return null;
  }
  if (!res.ok) {
    if (res.status === 404 || res.status === 400) return null;
    console.error(`broadcast contact_by_phone ${res.status}:`,
      (await res.text()).slice(0, 200));
    return null;
  }
  const data = await res.json().catch(() => null);
  if (!data) return null;
  const c = data.data || data;
  if (!c) return null;

  // ── PILOT DEBUG: показать структуру ответа MH ────────────────────────────
  // Логируем какие списки и какие channel_id видим — чтобы понять почему
  // валидация не находит targetChannelId.
  const listSummary = [];
  for (const [name, list] of [['users', c.users], ['channels', c.channels],
    ['channel_links', c.channel_links], ['contact_channels', c.contact_channels]]) {
    if (!Array.isArray(list)) { listSummary.push(`${name}=N/A`); continue; }
    const cids = list.map((x) => x && (x.channel_id ?? '?')).join(',');
    listSummary.push(`${name}=[${cids}]`);
  }
  console.log(`PILOT resolve phone=${maskPhone(phone)} needCreate=${needCreate} `
    + `target=${targetChannelId} lists: ${listSummary.join(' ')}`);

  for (const list of [c.users, c.channels, c.channel_links, c.contact_channels]) {
    if (!Array.isArray(list)) continue;
    for (const x of list) {
      if (!x) continue;
      const uid = x.user_id || x.id;
      const cid = x.channel_id;
      if (!uid) continue;
      if (Number(cid) !== Number(targetChannelId)) continue;
      if (x.blocked) continue;
      console.log(`PILOT resolve OK phone=${maskPhone(phone)} userId=${uid}`);
      return {
        channelUuid: targetChannelUuid,
        channelId: Number(targetChannelId),
        userId: uid,
        lastMessageAt: x.last_message || null,
      };
    }
  }
  console.log(`PILOT resolve NULL phone=${maskPhone(phone)} needCreate=${needCreate} `
    + `— ни один список не содержит channel_id=${targetChannelId}. `
    + `Top-level keys: ${Object.keys(c).join(',')}`);
  return null;
}

// Прямая отправка в message.help send_message без cold-фильтра / hour-cap.
// Эти проверки делает runBroadcastJob выше — нам нужен «тонкий» send.
async function mhSendDirect(env, token, channelUuid, userId, text) {
  const url = `${MH_API}/app/projects/${env.MH_PROJECT_ID}`
    + `/channels/${channelUuid}/send_message/${userId}`;
  console.log(`PILOT send start userId=${userId} channelUuid=${channelUuid.slice(0,8)}…`);
  for (let attempt = 0; attempt < 3; attempt++) {
    let res;
    try {
      const form = new FormData();
      form.append('text', text);
      form.append('destination', 'from_operator');
      res = await fetch(url, {
        method: 'POST',
        headers: { Authorization: `Bearer ${token}` },
        body: form,
      });
    } catch (e) {
      console.error(`PILOT send fetch attempt=${attempt} userId=${userId}:`, e && e.message);
      await sleep(500 * (attempt + 1));
      continue;
    }
    if (res.ok) {
      const data = await res.json().catch(() => null);
      const sentId = data && data.data && data.data.id;
      if (sentId) {
        await env.BOT_KV.put(`sent:${sentId}`, '1',
          { expirationTtl: SENT_TTL });
      }
      console.log(`PILOT send OK userId=${userId} attempt=${attempt} sentId=${sentId || 'none'}`);
      return true;
    }
    const bodyText = (await res.text()).slice(0, 300);
    console.error(`PILOT send FAIL userId=${userId} attempt=${attempt} status=${res.status} body=${bodyText}`);
    if (res.status !== 429 && res.status < 500) return false;
    const retryAfter = parseInt(res.headers.get('retry-after') || '0', 10);
    await sleep(retryAfter ? retryAfter * 1000 : 600 * (attempt + 1));
  }
  return false;
}

