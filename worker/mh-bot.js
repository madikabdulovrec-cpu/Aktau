async function callClaude(env, history, serviceNote) {
  // Слоты в промпт НЕ подмешиваем — бот не показывает временные слоты.
  // НО подмешиваем ТЕКУЩУЮ ДАТУ (Almaty) в последнее user-сообщение —
  // нужна для логики «акция действует до 15.06.2026». Подмешиваем только
  // в последнее сообщение, чтобы системный префикс и старые ходы остались
  // стабильными для prompt cache.
  const apiMessages = history.map((m) => ({ role: m.role, content: m.content }));
  // Дата — для логики акций, время — для обещаний клиенту («администратор
  // свяжется в ближайшее время» днём vs «напишет утром» ночью), см. раздел
  // «ВРЕМЯ СУТОК» в SYSTEM_PROMPT.
  const nowA = almatyNow();
  // День недели подаём ГОТОВЫМ (LLM плохо считают календарь и путают дни) —
  // иначе бот пишет в карточку «суббота 13.06», когда это пятница.
  const WEEKDAYS = ['воскресенье', 'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота'];
  const nowStr = `${nowA.ymd} (${WEEKDAYS[nowA.date.getUTCDay()]}), `
    + `${String(nowA.hour).padStart(2, '0')}:${String(nowA.minute).padStart(2, '0')}`;
  for (let i = apiMessages.length - 1; i >= 0; i--) {
    if (apiMessages[i].role === 'user') {
      apiMessages[i] = {
        role: 'user',
        content: `ТЕКУЩАЯ ДАТА И ВРЕМЯ (Алматы): ${nowStr}\n\n${apiMessages[i].content}`
          + (serviceNote ? `\n\n${serviceNote}` : ''),
      };
      break;
    }
  }

  const payload = {
    model: env.ANTHROPIC_MODEL || DEFAULT_MODEL,
    max_tokens: 1024,
    temperature: BOT_TEMPERATURE,
    system: [{ type: 'text', text: SYSTEM_PROMPT, cache_control: { type: 'ephemeral' } }],
    messages: apiMessages,
  };

  for (let attempt = 0; attempt < 3; attempt++) {
    let res;
    try {
      res = await fetch(ANTHROPIC_URL, {
        method: 'POST',
        headers: {
          'x-api-key': env.ANTHROPIC_API_KEY,
          'anthropic-version': ANTHROPIC_VERSION,
          'content-type': 'application/json',
        },
        body: JSON.stringify(payload),
      });
    } catch (e) {
      console.error('Claude fetch error:', e && e.message);
      await sleep(500 * (attempt + 1));
      continue;
    }

    if (res.ok) {
      const data = await res.json();
      const u = data.usage || {};
      console.log(`claude ok cache_read=${u.cache_read_input_tokens || 0} in=${u.input_tokens || 0} out=${u.output_tokens || 0}`);
      if (data.stop_reason === 'refusal') {
        console.error('Claude refusal — отдаём на менеджера');
        return '';
      }
      const textBlock = (data.content || []).find((b) => b.type === 'text');
      return textBlock ? textBlock.text.trim() : '';
    }

    // 429 / 5xx — ретраить; 4xx (кроме 429) — нет смысла
    if (res.status !== 429 && res.status < 500) {
      const body = (await res.text()).slice(0, 400);
      console.error(`Claude API ${res.status}:`, body.slice(0, 200));
      const low = body.toLowerCase();
      let kind = 'http';
      if (res.status === 401 || low.includes('authentication') || low.includes('invalid x-api-key') || low.includes('api key')) kind = 'apikey';
      else if (low.includes('credit') || low.includes('balance') || low.includes('billing') || low.includes('quota') || low.includes('insufficient')) kind = 'balance';
      await alertBotDown(env, kind, `HTTP ${res.status}`);
      return '';
    }
    const retryAfter = parseInt(res.headers.get('retry-after') || '0', 10);
    await sleep(retryAfter ? retryAfter * 1000 : 800 * (attempt + 1));
  }
  console.error('Claude API: retries exhausted');
  await alertBotDown(env, 'overload', 'повторы исчерпаны (429/5xx)');
  return '';
}

// ── Управляющие теги ────────────────────────────────────────────────────────
// [[BOOKING_JSON|{...}]] — КЭВ-карточка менеджеру (имя/процедура/день/интервал/…).
// [[OFFER_SLOTS|{...}]]  — запрос авто-записи: «клиент готов», система покажет слоты.
// [[BOOK_CONSULT|{...}]] — клиент выбрал слот (slot_ref — номер, НЕ время текстом).
// [[BOOKING|a|b|c|d|e]]  — легаси-формат КЭВ (обратная совместимость).
// [[HANDOFF|причина]]    — передать менеджеру.
// helper: типобезопасный JSON-объект тега или null.
function parseTagJson(raw) {
  try {
    const o = JSON.parse(raw);
    return (o && typeof o === 'object' && !Array.isArray(o)) ? o : null;
  } catch (_) { return null; }
}
const tagStr = (v) => (typeof v === 'string' ? v.trim() : '');

function parseControlTags(text) {
  let booking = null;
  let handoff = null;
  let offerSlots = null;
  let bookConsult = null;

  // [[BOOKING_JSON|{...}]]
  const jsonRe = /\[\[\s*BOOKING_JSON\s*\|\s*(\{[\s\S]*?\})\s*\]\]/gi;
  let jm;
  while ((jm = jsonRe.exec(text)) !== null) {
    const o = parseTagJson(jm[1]);
    if (!o) { console.error('BOOKING_JSON parse error'); continue; }
    booking = {
      name: tagStr(o.name),
      phone: tagStr(o.phone).replace(/\D/g, ''),
      service: tagStr(o.service),
      day: tagStr(o.day),
      interval: tagStr(o.interval),
      contraindications: tagStr(o.contra) || tagStr(o.contraindications),
      lang: (tagStr(o.lang).toLowerCase() === 'kz') ? 'kz' : 'ru',
      temp: (tagStr(o.temp).toLowerCase() === 'hot') ? 'hot' : 'warm',
    };
  }

  // [[OFFER_SLOTS|{...}]] — запрос слотов авто-записи.
  const offerRe = /\[\[\s*OFFER_SLOTS\s*\|\s*(\{[\s\S]*?\})\s*\]\]/gi;
  let om;
  while ((om = offerRe.exec(text)) !== null) {
    const o = parseTagJson(om[1]);
    if (!o) { console.error('OFFER_SLOTS parse error'); continue; }
    offerSlots = {
      name: tagStr(o.name),
      contra: tagStr(o.contra) || tagStr(o.contraindications),
      lang: (tagStr(o.lang).toLowerCase() === 'kz') ? 'kz' : 'ru',
      temp: (tagStr(o.temp).toLowerCase() === 'hot') ? 'hot' : 'warm',
      day_hint: tagStr(o.day_hint),
    };
  }

  // [[BOOK_CONSULT|{"slot_ref":"2"}]] — выбор слота. slot_ref ТОЛЬКО как строка/число.
  const bookRe = /\[\[\s*BOOK_CONSULT\s*\|\s*(\{[\s\S]*?\})\s*\]\]/gi;
  let bm;
  while ((bm = bookRe.exec(text)) !== null) {
    const o = parseTagJson(bm[1]);
    if (!o) { console.error('BOOK_CONSULT parse error'); continue; }
    const ref = (typeof o.slot_ref === 'string' || typeof o.slot_ref === 'number')
      ? String(o.slot_ref).trim() : '';
    bookConsult = { slot_ref: ref };
  }

  // Легаси [[BOOKING|...]] + [[HANDOFF|...]]
  const re = /\[\[\s*(BOOKING|HANDOFF)\s*\|([^\]]*)\]\]/gi;
  let match;
  while ((match = re.exec(text)) !== null) {
    const kind = match[1].toUpperCase();
    const payload = match[2].trim();
    if (kind === 'BOOKING') {
      if (!booking) {
        const p = payload.split('|').map((s) => s.trim());
        booking = { name: p[0] || '', phone: (p[1] || '').replace(/\D/g, ''),
          service: p[2] || '', day: p[3] || '', interval: '',
          contraindications: p[4] || '', lang: 'ru', temp: 'warm', legacy: true };
      }
    } else {
      handoff = payload || 'general';
    }
  }

  const cleanText = text
    .replace(jsonRe, '').replace(offerRe, '').replace(bookRe, '').replace(re, '')
    .replace(/\n{3,}/g, '\n\n').trim();
  return { cleanText, booking, handoff, offerSlots, bookConsult };
}

// Валидация карточки КЭВ. ok=false → тег не закрывает диалог, missing подмешается
// в следующий запрос Claude. Для легаси-формата day («слот») засчитывается как
// день+интервал. Телефон НЕ требуется (клиент пишет из WhatsApp, его номер у нас
// уже есть — handleBooking подставит из контакта). Возвращает нормализованный
// телефон, если клиент всё же его назвал (иначе '').
function validateBooking(b) {
  const missing = [];
  // Имя + фамилия: ждём минимум два слова (имя и фамилию). Одно слово — добираем
  // фамилию (мягко, как все недостающие поля), но НЕ блокируем намертво: если
  // клиент даёт только имя и больше ничего — это решает Claude по ходу диалога.
  const words = String(b.name || '').trim().split(/\s+/).filter(Boolean);
  if (!words.length) missing.push('имя и фамилия клиента');
  else if (words.length < 2) missing.push('фамилия клиента (есть только имя)');
  if (!b.service) missing.push('процедура/зона');
  if (b.legacy) {
    if (!b.day) missing.push('желаемый день и время');
  } else {
    if (!b.day) missing.push('желаемый день');
    if (!b.interval) missing.push('интервал времени (или пожелание клиента)');
  }
  if (!b.contraindications) missing.push('ответ по противопоказаниям (или «нет»)');
  return { ok: !missing.length, missing, phone: normalizePhone(b.phone) || '' };
}

