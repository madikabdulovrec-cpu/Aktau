// Текст подтверждения. partsList — список записей клиента на «завтра»
// (если у него несколько процедур подряд, шлём ОДНО сообщение со всеми
// временами). 3 микро-варианта приветствия/интро/CTA — точно по правилу
// message.help «1–3 шаблона текста на рассылку». Вариант детерминирован
// по record_id mod 3.
function buildConfirmationText(partsList, variant) {
  const v = ((Number(variant) || 0) % 3 + 3) % 3;
  // Совместимость: можно передать одну parts вместо массива
  const list = Array.isArray(partsList) ? partsList : [partsList];

  const fmt = (p) => ({
    date: `${String(p.day).padStart(2, '0')}.`
      + `${String(p.month).padStart(2, '0')}.${p.year}`,
    time: `${p.hour}:${String(p.minute).padStart(2, '0')}`,
  });

  const greet = [
    'Добрый день 🌷',
    'Здравствуйте 🌷',
    'Добрый день, M&M на связи ✨',
  ][v];

  const intro = [
    'Это автоматическое напоминание о вашей записи. Если в данных будут неточности — ответьте, и менеджер всё уточнит.',
    'Напоминаем о вашей записи. Если в деталях что-то не так — просто напишите, исправим.',
    'Это напоминание о записи. Если детали не совпадают — ответьте сообщением, поправим.',
  ][v];

  const ask = [
    'Подтвердите, пожалуйста, запись ❤️',
    'Подтвердите, пожалуйста, что придёте ❤️',
    'Подтвердите запись, пожалуйста',
  ][v];

  const lines = [greet, '', intro, ''];

  if (list.length === 1) {
    const f = fmt(list[0]);
    lines.push(
      'Вы записаны в M&M:',
      '',
      `🗓 Дата: ${f.date}`,
      `🕒 Время: ${f.time}`,
      '📍 Ауэзова 175 Б',
    );
  } else {
    // Несколько записей у одного клиента — группируем времена под общей датой
    // (если все в один день) или показываем дата+время построчно.
    const dates = new Set(list.map((p) => fmt(p).date));
    if (dates.size === 1) {
      const oneDate = list[0] ? fmt(list[0]).date : '';
      lines.push(
        `У вас в M&M ${list.length} записи на ${oneDate}:`,
        '',
      );
      for (const p of list) {
        lines.push(`🕒 ${fmt(p).time}`);
      }
      lines.push('📍 Ауэзова 175 Б');
    } else {
      lines.push('У вас в M&M несколько записей:', '');
      for (const p of list) {
        const f = fmt(p);
        lines.push(`🗓 ${f.date} в ${f.time}`);
      }
      lines.push('📍 Ауэзова 175 Б');
    }
  }

  lines.push('', ask, '', '❗ Отмена записи — минимум за 24 часа.',
    'При отмене менее чем за 24 часа предоплата/посещение сгорает.',
    '', 'M & M');

  // Ссылка 2gis — только в 1 из 3 вариантов (~33%). Длинная URL в каждом
  // сообщении читается Meta как маркетинг и повышает шанс спам-флага. Адрес
  // и так есть в тексте — клиент найдёт по нему.
  if (v === 0) {
    lines.push('', 'https://2gis.kz/almaty/geo/70000001060407110');
  }

  return lines.join('\n');
}

// ── Ответ клиента на подтверждение: Да / Нет ───────────────────────────────

function classifyConfirmationResponse(rawText) {
  if (!rawText) return null;
  let t = String(rawText).trim().toLowerCase();
  // Длинные/вопросительные ответы не считаем коротким Да/Нет — пусть Claude
  // разбирает в обычном flow (либо менеджер).
  if (t.length > 50) return null;
  if (t.indexOf('?') !== -1) return null;

  // Сначала «нет», потому что фразы «не приду / не получится» содержат «не»,
  // а «да» в них нет.
  if (/(^|\W)(нет|жок|joq|отмен|не приду|не буду|не получ|не смог|не прид|перенес|отказ|no|нету|👎|❌|✖|✗)(\W|$)/i.test(t)) {
    return 'no';
  }
  if (/(^|\W)(да|ия|иә|плюс|ок|окей|хорошо|подтвержд|конечно|приду|буду|yes|ага|угу|👍|✅|☑|✔)(\W|$)/i.test(t)
    || t === '1' || t === '+' || /(^|\W)\+(\W|$)/.test(t)) {
    return 'yes';
  }
  // Эмодзи-only без слов
  if (/^[\s👍✅☑✔❤❤️🌷👌]+$/u.test(t)) return 'yes';
  if (/^[\s👎❌✖✗]+$/u.test(t)) return 'no';
  return null;
}

async function handleConfirmationResponse(env, msg, kind, pending) {
  // Сбрасываем pending в любом случае — повторно не реагируем.
  await env.BOT_KV.delete(`confirm_pending:user:${msg.userId}`);

  if (kind === 'yes') {
    let altOk = false;
    if (pending && pending.recordId) {
      try { altOk = await markAttendanceConfirmed(env, pending.recordId); }
      catch (e) { console.error('attendance set error:', e && e.message); }
    }
    await sendMessage(env, msg, 'Спасибо! Ждём вас 🌷');
    // Локальная отметка на случай если Altegio не дался — менеджер увидит лог
    await env.BOT_KV.put(`confirm_done:${pending && pending.recordId}`, JSON.stringify({
      kind: 'confirmed', altegio: altOk, at: new Date().toISOString(),
      userId: msg.userId,
    }), { expirationTtl: LEAD_TTL });
    console.log(`confirm reply YES u${msg.userId} record=${pending && pending.recordId} altegio=${altOk}`);
    return;
  }

  if (kind === 'no') {
    await sendMessage(env, msg, 'Поняла, передаю менеджеру — он(а) свяжется и поможет 🤍');
    if (msg.userId) {
      await env.BOT_KV.put(`op:${msg.userId}`, '1', { expirationTtl: OPERATOR_PAUSE_TTL });
    }
    await env.BOT_KV.put(`confirm_done:${pending && pending.recordId}`, JSON.stringify({
      kind: 'cancel_requested', at: new Date().toISOString(),
      userId: msg.userId,
    }), { expirationTtl: LEAD_TTL });
    await assignToManager(env, msg);
    console.log(`confirm reply NO u${msg.userId} record=${pending && pending.recordId}`);
  }
}

// Клиент ответил на подтверждение НЕ короткое «Да/Нет», а вопросом или
// просьбой («можно перенести?», «во сколько было?», «не уверена пока»,
// «у меня плохое самочувствие»). Бот сам не отвечает — это не его уровень
// компетенции; нужно довести до менеджера. Работает в ЛЮБОЕ время суток.
async function handleConfirmationFollowUp(env, msg, pending) {
  await env.BOT_KV.delete(`confirm_pending:user:${msg.userId}`);

  await sendMessage(env, msg,
    'Поняла вас 🌷 Передаю менеджеру — он(а) свяжется в ближайшее время и поможет с записью.');

  if (msg.userId) {
    await env.BOT_KV.put(`op:${msg.userId}`, '1',
      { expirationTtl: OPERATOR_PAUSE_TTL });
  }

  await env.BOT_KV.put(`confirm_done:${pending && pending.recordId}`,
    JSON.stringify({
      kind: 'followup_to_manager',
      recordId: pending && pending.recordId,
      clientText: String(msg.text || '').slice(0, 300),
      at: new Date().toISOString(),
      userId: msg.userId,
    }), { expirationTtl: LEAD_TTL });

  await assignToManager(env, msg);
  console.log(`confirm reply FOLLOWUP u${msg.userId} `
    + `record=${pending && pending.recordId} `
    + `text="${String(msg.text || '').slice(0, 60)}"`);
}

// ── Парсеры даты Altegio (локальное время Almaty) ──────────────────────────

function parseAltegioParts(s) {
  if (!s) return null;
  const m = String(s).match(
    /^(\d{4})-(\d{1,2})-(\d{1,2})[ T](\d{1,2}):(\d{2})(?::(\d{2}))?/);
  if (!m) return null;
  return {
    year: +m[1], month: +m[2], day: +m[3],
    hour: +m[4], minute: +m[5], second: +(m[6] || 0),
  };
}

function partsToAlmatyMs(p) {
  // Altegio отдаёт datetime в локальном времени филиала (Almaty, UTC+5)
  // без таймзоны. Чтобы получить корректный ms-таймстамп, вычитаем смещение.
  return Date.UTC(p.year, p.month - 1, p.day,
    p.hour - ALMATY_UTC_OFFSET, p.minute, p.second);
}

// ── Утилиты телефонов и анти-бан ───────────────────────────────────────────

function normalizePhone(raw) {
  if (!raw) return null;
  const d = String(raw).replace(/\D/g, '');
  if (d.length < 10) return null;
  // 87xxxxxxxxx (Каз.) → 77xxxxxxxxx
  if (d.length === 11 && d[0] === '8') return '7' + d.slice(1);
  if (d.length === 11 && d[0] === '7') return d;
  if (d.length === 10) return '7' + d;
  return d;
}

function maskPhone(p) {
  if (!p) return '<none>';
  return String(p).slice(0, 4) + '***' + String(p).slice(-3);
}

function shuffleInPlace(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const tmp = arr[i]; arr[i] = arr[j]; arr[j] = tmp;
  }
  return arr;
}

// ════════════════════════════════════════════════════════════════════════════
// РАССЫЛКА (BROADCAST)
// Активируется через env.BROADCAST_ACTIVE='1'. Шлёт акции по базе активных
// клиентов Altegio строго через WA2 (channel 20916). Темплейты ротируются
// по часу. Полностью отдельный поток от confirmation: свой dedup, свой
// часовой счётчик, свой sleep.
// ════════════════════════════════════════════════════════════════════════════

async function runBroadcastJob(env) {
  if (env.BROADCAST_ACTIVE !== '1') return;
  if (!env.MH_LOGIN || !env.MH_PASSWORD || !env.MH_PROJECT_ID) {
    console.log('broadcast: message.help not configured, skip');
    return;
  }
  if (!env.ALTEGIO_PARTNER_TOKEN || !env.ALTEGIO_USER_TOKEN
    || !env.ALTEGIO_COMPANY_ID) {
    console.log('broadcast: altegio not configured, skip');
    return;
  }

  const now = almatyNow();
  if (now.hour >= BROADCAST_END_HOUR) {
    console.log(`broadcast: ended (h=${now.hour} >= ${BROADCAST_END_HOUR})`);
    return;
  }
  if (now.hour < CONFIRM_HOUR_START) {
    console.log(`broadcast: before start (h=${now.hour})`);
    return;
  }

  // startedAt — записываем в KV при первом tick'е дня
  const startedKey = `broadcast:started:${now.ymd}`;
  let startedAt = await env.BOT_KV.get(startedKey);
  if (!startedAt) {
    startedAt = new Date(now.ms).toISOString();
    await env.BOT_KV.put(startedKey, startedAt, { expirationTtl: 90000 });
    console.log(`broadcast: started at ${startedAt} (Almaty ${now.ymd} ${now.hour}:${String(now.minute).padStart(2,'0')})`);
  }
  const startedMs = new Date(startedAt).getTime();
  const hoursSinceStart = Math.floor((now.ms - startedMs) / 3600000);
  const templateIdx = ((hoursSinceStart % 3) + 3) % 3;

  // Часовой счётчик — hard cap 30/час
  const hourKey = `broadcast_hour:${now.ymdh}`;
  const hourUsed = Number(await env.BOT_KV.get(hourKey)) || 0;
  if (hourUsed >= BROADCAST_PER_HOUR) {
    console.log(`broadcast: hour cap reached (${hourUsed}/${BROADCAST_PER_HOUR}) at h=${now.hour}`);
    return;
  }
  const remainingThisHour = BROADCAST_PER_HOUR - hourUsed;
  const tickQuota = Math.min(BROADCAST_TICK_MAX, remainingThisHour);

  // База клиентов Altegio (кеш в KV на 6ч)
  const base = await fetchBroadcastBase(env);
  if (!base || !base.length) {
    console.log('broadcast: empty base, skip');
    return;
  }

  const token = await getMhToken(env);
  if (!token) {
    console.error('broadcast: no MH token');
    return;
  }

  shuffleInPlace(base);
  const text = BROADCAST_TEMPLATES[templateIdx];

  let sent = 0;
  let dedupSkip = 0;
  let noContactSkip = 0;
  let coldSkip = 0;
  let pendingSkip = 0;
  let opSkip = 0;

  for (const client of base) {
    if (sent >= tickQuota) break;

    const phone = normalizePhone(client.phone);
    if (!phone) continue;

    if (await env.BOT_KV.get(`broadcast_sent:${phone}`)) { dedupSkip++; continue; }

    const resolved = await mhResolveContactStrict(env, token, phone,
      BROADCAST_CHANNEL_ID, BROADCAST_CHANNEL_UUID);
    if (!resolved) { noContactSkip++; continue; }

    // Фильтр холодных (>90 дней без сообщений)
    if (resolved.lastMessageAt) {
      const last = parseAltegioParts(resolved.lastMessageAt);
      const lastMs = last ? partsToAlmatyMs(last) : null;
      if (lastMs && (Date.now() - lastMs) > BROADCAST_COLD_DAYS * 86400000) {
        coldSkip++;
        continue;
      }
    }

    // Не лезем в чат, где клиент ждёт ответ на подтверждение
    if (await env.BOT_KV.get(`confirm_pending:user:${resolved.userId}`)) {
      pendingSkip++;
      continue;
    }
    // Не лезем в чат, где менеджер уже работает
    if (await env.BOT_KV.get(`op:${resolved.userId}`)) {
      opSkip++;
      continue;
    }

    const ok = await mhSendDirect(env, token,
      BROADCAST_CHANNEL_UUID, resolved.userId, text);
    if (!ok) {
      console.error(`broadcast: send failed phone=${maskPhone(phone)}`);
      continue;
    }

    sent++;
    await env.BOT_KV.put(`broadcast_sent:${phone}`, JSON.stringify({
      sentAt: new Date().toISOString(),
      templateIdx, userId: resolved.userId,
    }), { expirationTtl: BROADCAST_DEDUP_TTL });
    await env.BOT_KV.put(hourKey, String(hourUsed + sent),
      { expirationTtl: BROADCAST_HOUR_COUNTER_TTL });

    if (sent < tickQuota) {
      await sleep(BROADCAST_TICK_PAUSE_MIN
        + Math.floor(Math.random()
          * (BROADCAST_TICK_PAUSE_MAX - BROADCAST_TICK_PAUSE_MIN)));
    }
  }

  console.log(`broadcast tick: base=${base.length}, h=${now.hour}:${String(now.minute).padStart(2,'0')}, `
    + `template=${templateIdx + 1}, hour_used=${hourUsed + sent}/${BROADCAST_PER_HOUR}, `
    + `this_tick=${sent}, dedup=${dedupSkip}, no_contact=${noContactSkip}, `
    + `cold=${coldSkip}, pending=${pendingSkip}, op=${opSkip}`);
}

// Выгрузка активной базы клиентов из Altegio с кешем в KV на BASE_CACHE_TTL.
// Берём всех у кого visit_count > 0 и есть телефон. Источник: clients/search
// с пагинацией. Один tick загружает базу за ~10-30 сек, потом 6ч из кеша.
async function fetchBroadcastBase(env) {
  const cacheKey = `broadcast:base:${almatyNow().ymd}`;
  const cached = await env.BOT_KV.get(cacheKey, { type: 'json' });
  if (cached && Array.isArray(cached) && cached.length) return cached;

  const out = [];
  for (let page = 1; page <= 30; page++) {
    const url = `${ALTEGIO_API}/company/${env.ALTEGIO_COMPANY_ID}/clients/search`;
    let res;
    try {
      res = await fetch(url, {
        method: 'POST',
        headers: altegioHeaders(env),
        body: JSON.stringify({
          page,
          page_size: 200,
          fields: ['id', 'phone', 'name', 'visit_count', 'last_visit_date'],
          filters: [],
        }),
      });
    } catch (e) {
      console.error(`broadcast base page ${page}:`, e && e.message);
      break;
    }
    if (!res.ok) {
      console.error(`broadcast base page ${page}: HTTP ${res.status}`);
      break;
    }
    const data = await res.json().catch(() => null);
    const list = (data && data.data) || [];
    if (!list.length) break;
    for (const c of list) {
      if (!c || !c.phone) continue;
      if (Number(c.visit_count) === 0) continue;
      out.push({ phone: c.phone, name: c.name });
    }
    if (list.length < 200) break;
  }

  console.log(`broadcast: base fetched ${out.length} clients`);
  await env.BOT_KV.put(cacheKey, JSON.stringify(out),
    { expirationTtl: BROADCAST_BASE_CACHE_TTL });
  return out;
}

// Строгий резолв контакта по телефону: ТОЛЬКО на канале BROADCAST_CHANNEL_ID.
// Если клиент на нём не писал — возвращает null (не открываем новый чат).
async function mhResolveContactStrict(env, token, phone,
  targetChannelId, targetChannelUuid) {
  let res;
  try {
    res = await fetch(
      `${MH_API}/app/projects/${env.MH_PROJECT_ID}/contacts/contact_by_phone`,
      {
        method: 'POST',
        headers: { Authorization: `Bearer ${token}`,
          'content-type': 'application/json' },
        body: JSON.stringify({ phone, need_create: false }),
      });
  } catch (e) {
    console.error('broadcast contact_by_phone:', e && e.message);
    return null;
  }
  if (!res.ok) {
    if (res.status === 404 || res.status === 400) return null;
    console.error(`broadcast contact_by_phone ${res.status}:`,
      (await res.text()).slice(0, 200));
    return null;
  }
  const data = await res.json().catch(() => null);
  if (!data) return null;
  const c = data.data || data;
  if (!c) return null;

  for (const list of [c.users, c.channels, c.channel_links, c.contact_channels]) {
    if (!Array.isArray(list)) continue;
    for (const x of list) {
      if (!x) continue;
      const uid = x.user_id || x.id;
      const cid = x.channel_id;
      if (!uid) continue;
      if (Number(cid) !== Number(targetChannelId)) continue;
      if (x.blocked) continue;
      return {
        channelUuid: targetChannelUuid,
        channelId: Number(targetChannelId),
        userId: uid,
        lastMessageAt: x.last_message || null,
      };
    }
  }
  return null;
}

// Прямая отправка в message.help send_message без cold-фильтра / hour-cap.
// Эти проверки делает runBroadcastJob выше — нам нужен «тонкий» send.
async function mhSendDirect(env, token, channelUuid, userId, text) {
  const url = `${MH_API}/app/projects/${env.MH_PROJECT_ID}`
    + `/channels/${channelUuid}/send_message/${userId}`;
  for (let attempt = 0; attempt < 3; attempt++) {
    let res;
    try {
      const form = new FormData();
      form.append('text', text);
      form.append('destination', 'from_operator');
      res = await fetch(url, {
        method: 'POST',
        headers: { Authorization: `Bearer ${token}` },
        body: form,
      });
    } catch (e) {
      console.error('broadcast send fetch:', e && e.message);
      await sleep(500 * (attempt + 1));
      continue;
    }
    if (res.ok) {
      const data = await res.json().catch(() => null);
      const sentId = data && data.data && data.data.id;
      if (sentId) {
        await env.BOT_KV.put(`sent:${sentId}`, '1',
          { expirationTtl: SENT_TTL });
      }
      return true;
    }
    if (res.status !== 429 && res.status < 500) {
      console.error(`broadcast send ${res.status}:`,
        (await res.text()).slice(0, 200));
      return false;
    }
    const retryAfter = parseInt(res.headers.get('retry-after') || '0', 10);
    await sleep(retryAfter ? retryAfter * 1000 : 600 * (attempt + 1));
  }
  return false;
}

